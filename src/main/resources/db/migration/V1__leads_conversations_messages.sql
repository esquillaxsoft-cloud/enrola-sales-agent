-- Conversation state for an async SMS agent. A lead may reply days later, so everything the
-- next turn needs lives here, not in memory or in OpenAI's stored responses.
-- Written as PostgreSQL; H2 runs it in PostgreSQL mode.

-- Snapshot of the lead as received from Enrola's lead API.
create table lead (
    id               bigint generated by default as identity primary key,
    external_id      varchar(64)  not null unique,  -- the platform's lead id
    given_name       varchar(100) not null,
    phone            varchar(20)  not null,
    email            varchar(255),
    state            varchar(3)   not null,         -- AU state; drives the lead's time zone
    current_provider varchar(100),                  -- null when the lead has no insurer
    current_premium  varchar(50),                   -- free text from Comparato, e.g. '$350-$450'
    created_at       timestamp with time zone not null,
    constraint lead_state_check check (state in ('ACT', 'NSW', 'NT', 'QLD', 'SA', 'TAS', 'VIC', 'WA'))
);

-- One conversation per lead. "Goal met" and "unsubscribed" are derived from status rather than
-- stored, so the flags sent to the platform can never disagree with the status.
create table conversation (
    id                   bigint generated by default as identity primary key,
    lead_id              bigint       not null unique references lead (id),
    status               varchar(16)  not null,
    end_reason           varchar(16),
    objection_count      integer      not null default 0,
    agent_version        varchar(64)  not null,  -- e.g. 'comparato/v1'; pinned for the conversation
    locale               varchar(16)  not null,  -- e.g. 'en_AU'; pinned for the conversation
    booking_event_id     varchar(64),            -- current Calendly booking, if any
    booking_start_time   timestamp with time zone,
    booking_advisor_name varchar(100),
    version              bigint       not null default 0,  -- optimistic lock: one turn at a time
    created_at           timestamp with time zone not null,
    constraint conversation_status_check
        check (status in ('ACTIVE', 'BOOKED', 'OPTED_OUT', 'DECLINED', 'ENDED')),
    constraint conversation_end_reason_check
        check ((status = 'ENDED') = (end_reason is not null)),
    constraint conversation_booking_check
        check ((booking_event_id is null) = (booking_start_time is null))
);

-- Every SMS in or out. Agent messages record how they were produced: a template key for
-- code-rendered messages (opener, booking confirmation), or the model's structured output.
create table message (
    id              bigint generated by default as identity primary key,
    conversation_id bigint        not null references conversation (id) on delete cascade,
    sender          varchar(8)    not null,
    body            varchar(1600) not null,  -- longest concatenated SMS; outbound is capped at 320 in code
    template_key    varchar(64),
    agent_output    varchar(16000),          -- JSON; varchar rather than json/clob to stay portable
    created_at      timestamp with time zone not null,
    constraint message_sender_check check (sender in ('LEAD', 'AGENT')),
    constraint message_lead_has_no_agent_fields
        check (sender = 'AGENT' or (template_key is null and agent_output is null))
);

create index message_conversation_idx on message (conversation_id, id);
